// =============================================================================
// Le lecteur de verdict (relecture indépendante, lot 3a).
//
// Le verdict d'une session de relecture est un commentaire de la PR, de forme fixe, que la machine lit :
//
//   <!-- relecture:verdict -->
//   Sommet relu: <40 caractères hexadécimaux, en minuscules>
//   Tour: <entier, 1 ou plus, sans zéro de tête>
//   Verdict: validé | refusé | incomplet
//   Bloquants: <entier, 0 ou plus>
//   Session: <identifiant>
//   /security-review: lancée | non requise        (facultative, dernière ligne de l'en-tête)
//
// puis une ligne vide et les constats, que le lecteur ne lit pas. `validé` veut zéro bloquant, `refusé` un au
// moins.
//
// Quel commentaire compte : celui d'un compte `OWNER`, `MEMBER` ou `COLLABORATOR`, jamais modifié après sa
// création. Un champ qui manque à la lecture est une lecture en échec (`LectureIllisible`), jamais un état.
// Un verdict à la marque dont la forme est fausse n'est jamais « validé » : il se lit `incomplet` quand ses
// lignes `Tour:` et `Session:` se lisent, sinon il est écarté.
//
// Module pur : aucun point d'entrée, aucun import, aucune horloge.
// =============================================================================

export const MARQUE_VERDICT = '<!-- relecture:verdict -->';
export const ASSOCIATIONS = ['OWNER', 'MEMBER', 'COLLABORATOR'];
export const PIED = '_Generated by [Claude Code](https://claude.ai/code)_';

export class LectureIllisible extends Error {
  constructor(message) {
    super(message);
    this.name = 'LectureIllisible';
  }
}

const FIN_CLOUD = `\n\n---\n${PIED}`;
const CHAMPS = ['body', 'created_at', 'updated_at', 'author_association'];

/**
 * Le corps tel qu'il se lit : forme NFC, `\r\n` ramenés à `\n`, blancs de bord retirés, puis le pied de page
 * des sessions cloud retiré s'il termine le corps. Un pied altéré reste dans le corps.
 * @param {string} corps
 * @returns {string}
 */
export function corpsLu(corps) {
  const net = String(corps).normalize('NFC').replace(/\r\n/g, '\n').trim();
  return net.endsWith(FIN_CLOUD) ? net.slice(0, -FIN_CLOUD.length).trimEnd() : net;
}

/**
 * @typedef {object} Commentaire  un commentaire de PR tel que l'API REST de GitHub le rend
 *   (`GET /repos/{dépôt}/issues/{n}/comments`) ; seuls ces champs sont lus
 * @property {number|string} [id]
 * @property {string} body
 * @property {string} created_at          ISO 8601
 * @property {string} updated_at
 * @property {string} author_association
 *
 * @param {Commentaire[]} commentaires  dans l'ordre de création
 * @returns {{ retenus: { id: unknown, rang: number, date: string, corps: string }[],
 *             ecartes: { id: unknown, rang: number, motif: 'auteur'|'edite', corps: string }[] }}
 *   `rang` : la place dans le tableau reçu, 0 pour le premier ; `date` : `created_at` ; `corps` : `corpsLu(body)`.
 *   `auteur` se juge avant `edite`.
 * @throws {LectureIllisible}
 */
export function retenir(commentaires) {
  if (!Array.isArray(commentaires)) throw new LectureIllisible('les commentaires ne sont pas un tableau');
  const retenus = [];
  const ecartes = [];
  let precedente = -Infinity;
  commentaires.forEach((c, rang) => {
    if (c === null || typeof c !== 'object') throw new LectureIllisible(`commentaire de rang ${rang} : pas un objet`);
    for (const champ of CHAMPS) if (typeof c[champ] !== 'string') throw new LectureIllisible(`commentaire de rang ${rang} : champ ${champ} absent`);
    const instant = Date.parse(c.created_at);
    if (Number.isNaN(instant)) throw new LectureIllisible(`commentaire de rang ${rang} : created_at n'est pas une date`);
    if (instant < precedente) throw new LectureIllisible(`commentaire de rang ${rang} : hors de l'ordre de création`);
    precedente = instant;
    const lu = { id: c.id, rang, date: c.created_at, corps: corpsLu(c.body) };
    if (!ASSOCIATIONS.includes(c.author_association)) ecartes.push({ id: lu.id, rang, motif: 'auteur', corps: lu.corps });
    else if (c.updated_at !== c.created_at) ecartes.push({ id: lu.id, rang, motif: 'edite', corps: lu.corps });
    else retenus.push(lu);
  });
  return { retenus, ecartes };
}

// Les lignes de l'en-tête, dans l'ordre : l'étiquette, la clé rendue, la forme de la valeur, sa lecture.
const entier = (texte) => (Number.isSafeInteger(Number(texte)) ? Number(texte) : null);
const mot = (texte) => texte;
const LIGNES = [
  { nom: 'Sommet relu', cle: 'sommet', forme: /^[0-9a-f]{40}$/, lire: mot },
  { nom: 'Tour', cle: 'tour', forme: /^[1-9][0-9]*$/, lire: entier },
  { nom: 'Verdict', cle: 'verdict', forme: /^(?:validé|refusé|incomplet)$/, lire: mot },
  { nom: 'Bloquants', cle: 'bloquants', forme: /^(?:0|[1-9][0-9]*)$/, lire: entier },
  { nom: 'Session', cle: 'session', forme: /^[A-Za-z0-9][A-Za-z0-9_-]*$/, lire: mot },
  { nom: '/security-review', cle: 'securite', forme: /^(?:lancée|non requise)$/, lire: mot },
];
const nomDe = (ligne) => LIGNES.find((l) => ligne.startsWith(`${l.nom}:`))?.nom ?? null;

/**
 * @typedef {object} VerdictLu
 * @property {string|null} sommet                       `null` quand sa ligne ne se lit pas
 * @property {number|null} tour
 * @property {'validé'|'refusé'|'incomplet'} verdict    `incomplet` dès que `illisible`
 * @property {number|null} bloquants
 * @property {string|null} session
 * @property {'lancée'|'non requise'|null} securite     `null` : ligne absente, ou d'une autre valeur
 * @property {boolean} illisible
 * @property {string[]} defauts                         vide quand `illisible` est faux
 *
 * @param {string} corps  déjà passé par `corpsLu`
 * @returns {VerdictLu|null}  `null` : le corps n'est pas à la marque (sa première ligne, exactement)
 */
export function lireVerdict(corps) {
  const lignes = String(corps).split('\n');
  if (lignes[0] !== MARQUE_VERDICT) return null;
  const vide = lignes.indexOf('', 1);
  const entete = lignes.slice(1, vide === -1 ? lignes.length : vide);
  const defauts = [];

  // La forme d'ensemble : cinq lignes dans l'ordre, ou six avec `/security-review:` en dernier, rien d'autre.
  const noms = entete.map(nomDe);
  const attendus = LIGNES.map((l) => l.nom);
  const dansLOrdre = (n) => noms.length === n && noms.every((nom, i) => nom === attendus[i]);
  if (!dansLOrdre(5) && !dansLOrdre(6)) defauts.push("en-tête : cinq lignes dans l'ordre (Sommet relu, Tour, Verdict, Bloquants, Session), ou six avec /security-review en dernier, et aucune autre");

  // Chaque valeur, cherchée par le préfixe de sa ligne où qu'elle soit : un verdict illisible doit pouvoir être
  // rattaché à son tour et à sa session.
  const lu = {};
  for (const { nom, cle, forme, lire } of LIGNES) {
    const ligne = entete.find((l) => l.startsWith(`${nom}:`));
    lu[cle] = null;
    if (ligne === undefined) continue;
    const valeur = ligne.startsWith(`${nom}: `) ? ligne.slice(nom.length + 2) : null;
    if (valeur !== null && forme.test(valeur)) lu[cle] = lire(valeur);
    if (lu[cle] === null) defauts.push(`${nom} : valeur hors de sa forme`);
  }
  if (lu.verdict === 'validé' && lu.bloquants !== null && lu.bloquants > 0) defauts.push('validé avec des bloquants');
  if (lu.verdict === 'refusé' && lu.bloquants === 0) defauts.push('refusé sans bloquant');

  const illisible = defauts.length > 0;
  return {
    sommet: lu.sommet,
    tour: lu.tour,
    verdict: illisible || lu.verdict === null ? 'incomplet' : lu.verdict,
    bloquants: lu.bloquants,
    session: lu.session,
    securite: lu.securite,
    illisible,
    defauts,
  };
}

/**
 * @param {Commentaire[]} commentaires
 * @returns {{ verdicts: (VerdictLu & { id: unknown, rang: number, date: string, tour: number, session: string })[],
 *             ecartes: { id: unknown, rang: number, motif: 'auteur'|'edite'|'illisible', defauts?: string[] }[] }}
 *   `verdicts`, dans l'ordre reçu : les commentaires retenus, à la marque, dont `Tour:` et `Session:` se lisent.
 *   `ecartes`, par rang croissant : les commentaires **à la marque** que `retenir` a écartés (`auteur`, `edite`,
 *   sans `defauts`), et ceux dont `Tour:` ou `Session:` ne se lit pas (`illisible`, avec `defauts`). Un
 *   commentaire qui n'est pas à la marque n'apparaît nulle part.
 * @throws {LectureIllisible}
 */
export function lireVerdicts(commentaires) {
  const { retenus, ecartes: hors } = retenir(commentaires);
  const verdicts = [];
  const ecartes = hors.filter((e) => lireVerdict(e.corps) !== null).map(({ id, rang, motif }) => ({ id, rang, motif }));
  for (const { id, rang, date, corps } of retenus) {
    const v = lireVerdict(corps);
    if (v === null) continue;
    if (v.tour === null || v.session === null) ecartes.push({ id, rang, motif: 'illisible', defauts: v.defauts });
    else verdicts.push({ id, rang, date, ...v });
  }
  return { verdicts, ecartes: ecartes.sort((a, b) => a.rang - b.rang) };
}

/**
 * L'en-tête d'un verdict, sans ligne vide finale ; la session de relecture le fait suivre d'une ligne vide et
 * de ses constats. `securite` absent ou `null` : pas de ligne `/security-review:`.
 * @param {{ sommet: string, tour: number, verdict: string, bloquants: number, session: string, securite?: string|null }} v
 * @returns {string}
 * @throws {TypeError}  quand ce qu'il écrirait ne se relit pas sans défaut par `lireVerdict`
 */
export function ecrireVerdict(v) {
  if (v === null || typeof v !== 'object') throw new TypeError('verdict : un objet est attendu');
  const voulu = { sommet: v.sommet, tour: v.tour, verdict: v.verdict, bloquants: v.bloquants, session: v.session, securite: v.securite ?? null };
  const lignes = [MARQUE_VERDICT, `Sommet relu: ${voulu.sommet}`, `Tour: ${voulu.tour}`, `Verdict: ${voulu.verdict}`, `Bloquants: ${voulu.bloquants}`, `Session: ${voulu.session}`];
  if (voulu.securite !== null) lignes.push(`/security-review: ${voulu.securite}`);
  const texte = lignes.join('\n');
  const relu = lireVerdict(texte);
  if (relu === null || relu.illisible) throw new TypeError(`verdict hors de la forme : ${relu === null ? 'marque absente' : relu.defauts.join(' ; ')}`);
  for (const cle of Object.keys(voulu)) if (relu[cle] !== voulu[cle]) throw new TypeError(`verdict hors de la forme : ${cle}`);
  return texte;
}
