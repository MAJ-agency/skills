#!/usr/bin/env bash
# =============================================================================
# Renvoie une PR de la file à sa session (skill `fusionner`) : retire `à-fusionner`,
# pose `fusion-bloquée`, commente la cause et nomme qui prévenir. Régime 7 : le worktree propriétaire (list_sessions →
# send_message). Régime 8 (A-244) : `session de la demande` et `conducteur de la demande`, ceux de la dernière demande
# `À relire` intacte de la PR, ou une ligne « aucune demande À relire intacte » / « demande illisible » qui renvoie au
# conducteur du chantier, sinon à son lanceur. La suite que le commentaire donne suit le régime
# de la PR (A-97) : en régime 8, corriger puis redemander la relecture (`à-relire`), jamais `à-fusionner`.
#
# Usage : bash scripts/chaine/renvoyer.sh <numéro> <cause>
# =============================================================================
set -euo pipefail
N=${1:?usage : renvoyer.sh <numéro> <cause>}
shift
cause=${*:?cause du renvoi manquante}
outils=$(cd "$(dirname "$0")" && pwd)
. "$outils/github.sh"

deja=$(renvois_de "$N")
plafond=$(plafond_renvois)
numero=$((deja + 1))
# Le régime de la PR (A-97, lot 5c) : en régime 8, l'auteur ne pose jamais `à-fusionner`, il redemande la relecture (A-91,
# A-93) ; le Relecteur pose `à-fusionner` sur un verdict validé et retire `fusion-bloquée`. PR ou régime illisibles : le
# texte du régime 7.
regime=7
# Sans la clé `relecture` sur develop ni sur aucun sujet (lecture locale, sans appel), le régime 7 sans lecture de plus.
cle=1
for r in $(git for-each-ref --format='%(refname)' refs/remotes/origin/develop refs/remotes/origin/sujet/); do
  ! cle_relecture_sur "$r" || { cle=0; break; }
done
if [ "$cle" = 0 ] && pr=$(pr_json "$N" 2>/dev/null); then
  base=$(jq -r .base.ref <<<"$pr")
  # Une PR empilée (sa base n'est ni develop ni un sujet) se lit sur develop, où elle sera reciblée, comme passer.sh :
  # en régime 8, son renvoi lui dit de demander sa relecture, jamais de remettre `à-fusionner`.
  case $base in develop | sujet/*) ;; *) base=develop ;; esac
  regime=$(regime_de_la_pr "$base" "$(jq -r '.created_at // ""' <<<"$pr")" 2>/dev/null) || regime=7
fi
if [ "$regime" = 8 ]; then
  suite="Corriger, puis redemander la relecture : $DEMANDE_DE_RELECTURE ; puis l'étiquette \`à-relire\`, sans retirer \`fusion-bloquée\` ; jamais \`à-fusionner\`, que le Relecteur pose sur un verdict validé (relecture indépendante, régime 8)."
else
  suite="Corriger, puis retirer \`fusion-bloquée\` et remettre \`à-fusionner\` (CLAUDE.md § « Fusion vers \`develop\` »)."
fi
# Une réception de develop faite en plusieurs fusions ne se corrige pas par un push : elle se refait, dans une nouvelle PR.
case "$cause" in
  *"jamais une seconde fusion"*)
    if [ "$regime" = 8 ]; then
      suite="Refaire la réception comme la cause le dit, ouvrir une nouvelle PR vers le sujet et fermer celle-ci ; la nouvelle PR demande sa relecture, $DEMANDE_DE_RELECTURE ; puis l'étiquette \`à-relire\`, jamais \`à-fusionner\` (relecture indépendante, régime 8)."
    else
      suite="Refaire la réception comme la cause le dit, ouvrir une nouvelle PR vers le sujet et fermer celle-ci ; la nouvelle PR porte \`à-fusionner\` (CLAUDE.md § « Fusion vers \`develop\` »)."
    fi ;;
esac
if [ "$numero" -ge "$plafond" ]; then
  suite="**Renvoi $numero sur $plafond : cette PR attend un humain.** La file ne la reprend plus ; un humain décide, puis le capitaine la passe à la main (\`passer.sh $N\`, ou \`sujet.sh fusionner $N\` pour une sous-PR)."
fi

poser_label "$N" fusion-bloquée
retirer_label "$N" à-fusionner
commenter "$N" "**Renvoyée par le capitaine de fusion** : $cause.

$suite

$MARQUE_RENVOI

---
_Generated by [Claude Code](https://claude.ai/code)_"
echo "[#$N] RENVOI : $cause"
[ "$numero" -lt "$plafond" ] || echo "[#$N] RENVOI $numero sur $plafond : la PR attend un humain"
if [ "$regime" = 8 ]; then
  # Régime 8 (A-244) : les sessions que la dernière demande `À relire` intacte nomme ; chaque session tourne dans son
  # propre conteneur, le worktree d'un propriétaire n'existe pas chez le capitaine. Sans demande lisible, le renvoi va
  # au lanceur (A-256 (3)) ; le renvoi lui-même est déjà posé.
  rc=0
  erreur=$(mktemp)
  ligne=$(demande_de_la_pr "$N" 2>"$erreur") || rc=$?
  cause_demande=$(grep . "$erreur" | tail -n 1 || :)
  rm -f "$erreur"
  case $rc in
    0)
      echo "[#$N] session de la demande : ${ligne%% *}"
      echo "[#$N] conducteur de la demande : ${ligne#* }" ;;
    1)
      echo "[#$N] session de la demande : —"
      echo "[#$N] conducteur de la demande : —"
      echo "[#$N] aucune demande À relire intacte sur la PR : prévenir le conducteur du chantier, sinon son lanceur" ;;
    *)
      echo "[#$N] demande illisible (${cause_demande:-code $rc}) : prévenir le conducteur du chantier, sinon son lanceur" ;;
  esac
else
  branche=$(gh api "$DEPOT/pulls/$N" --jq .head.ref)
  echo "[#$N] worktree propriétaire : $(bash "$outils/proprietaire.sh" "$branche" 2>/dev/null | tr '\n' ' ')"
fi
